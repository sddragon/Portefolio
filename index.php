    <h2>Veille technologique</h2>
    <p>La veille technologique est un processus continu qui consiste à rechercher, collecter, analyser puis exploiter des informations pour repérer les tendances et les innovations techniques.</p>

    <h3>Ma veille sur le thème de l'informatique</h3>

    <div class="projet">
      <h4>1. L'IA agentique</h4>
      <p>Des IA capables d'agir de façon autonome, de planifier et d'exécuter des tâches complexes sans intervention humaine directe.</p>
      <p><strong>Enjeux :</strong> automatisation de tâches, copilotes en entreprise, mais aussi fiabilité, contrôle et responsabilité.</p>
    </div>

    <div class="projet">
      <h4>2. Edge computing</h4>
      <p>Traitement des données au plus près de la source (capteurs, appareils) plutôt que dans le cloud.</p>
      <p><strong>Enjeux :</strong> latence réduite, moins de données envoyées au cloud, meilleure confidentialité.</p>
    </div>

    <div class="projet">
      <h4>3. Informatique quantique et cryptographie post-quantique</h4>
      <p>Utilisation de qubits pour résoudre des problèmes très complexes. La cryptographie post-quantique prépare la sécurité face aux futurs ordinateurs quantiques.</p>
      <p><strong>Enjeux :</strong> optimisation, simulation, et menace sur les cryptographies actuelles.</p>
    </div>

    <div class="projet">
      <h4>4. Connectivité 5G / 6G</h4>
      <p>Réseaux avec des débits très élevés, une latence très faible et une connexion massive d'objets (IoT).</p>
      <p><strong>Enjeux :</strong> villes intelligentes, véhicules autonomes, réalité étendue, services en temps réel.</p>
    </div>

    <div class="projet">
      <h4>5. Spatial computing et interfaces immersives</h4>
      <p>Mélange du monde physique et numérique grâce à la réalité augmentée, virtuelle ou mixte.</p>
      <p><strong>Enjeux :</strong> formation, maintenance, simulation et collaboration à distance.</p>
    </div>
